        // 动态内存缓存（由 CurriculumConfigService 实时更新）
        private static Dictionary<string, List<string>> _dynamicGradeSubjects = new Dictionary<string, List<string>>(DefaultGradeSubjects);
        private static Dictionary<string, List<string>> _dynamicSubjectCategories = new Dictionary<string, List<string>>(DefaultSubjectCategories);

        public static void SyncDynamicCurriculum(Dictionary<string, List<string>> gradeSubjects, Dictionary<string, List<string>> subjectCategories)
        {
            if (gradeSubjects != null && gradeSubjects.Count > 0)
            {
                _dynamicGradeSubjects = new Dictionary<string, List<string>>(gradeSubjects);
            }
            if (subjectCategories != null && subjectCategories.Count > 0)
            {
                _dynamicSubjectCategories = new Dictionary<string, List<string>>(subjectCategories);
            }
        }

        public static List<string> GetSubjectsByGrade(string grade)
        {
            if (!string.IsNullOrWhiteSpace(grade) && _dynamicGradeSubjects.TryGetValue(grade, out var subjects) && subjects.Count > 0)
            {
                return new List<string>(subjects);
            }
            if (!string.IsNullOrWhiteSpace(grade) && DefaultGradeSubjects.TryGetValue(grade, out var defaultSubjects))
            {
                return new List<string>(defaultSubjects);
            }
            return new List<string> { "数学", "语文", "英语", "物理", "化学", "生物", "道德与法治", "历史", "地理" };
        }

        public static List<string> GetCategoriesBySubject(string subject)
        {
            if (!string.IsNullOrWhiteSpace(subject) && _dynamicSubjectCategories.TryGetValue(subject, out var categories) && categories.Count > 0)
            {
                return new List<string>(categories);
            }
            if (!string.IsNullOrWhiteSpace(subject) && DefaultSubjectCategories.TryGetValue(subject, out var defaultCats))
            {
                return new List<string>(defaultCats);
            }
            return new List<string> { "全部", "基础概念", "核心考点", "重难点突破", "综合提升" };
        }

        public static List<string> GetAllSubjects()
        {
            var subjects = new HashSet<string>();
            foreach (var list in _dynamicGradeSubjects.Values)
            {
                foreach (var s in list) subjects.Add(s);
            }
            foreach (var s in _dynamicSubjectCategories.Keys)
            {
                subjects.Add(s);
            }
            return subjects.ToList();
        }
